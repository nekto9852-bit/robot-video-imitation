"""Unit tests for forward/inverse kinematics and the retargeting stage."""

import numpy as np
import pytest

from pose_to_trajectories import (
    build_robot,
    default_config,
    make_demo_landmarks,
    retarget_landmarks_to_angles,
    solve_ik_dls,
)


@pytest.fixture
def cfg():
    return default_config()


@pytest.fixture
def robot(cfg):
    return build_robot(cfg)


def test_fk_zero_pose_straight_up(robot):
    """With all joints at zero the arm points straight up along the base axis."""
    ee = robot.fk(np.zeros(6))
    expected_height = robot.link_lengths.sum() + robot.tool_offset
    assert np.allclose(ee, [0.0, 0.0, expected_height], atol=1e-9)


def test_jacobian_matches_first_order_motion(robot):
    """Jacobian predicts the first-order FK response along a small step."""
    q = np.array([0.1, -0.3, 0.2, -0.5, 0.4, 0.1])
    dq = np.array([0.02, -0.03, 0.05, 0.04, -0.02, 0.03])
    jac = robot.jacobian(q)
    eps = 1e-4
    predicted = jac @ dq
    actual = (robot.fk(q + eps * dq) - robot.fk(q)) / eps
    assert np.allclose(predicted, actual, atol=1e-5)


def test_ik_reaches_reachable_targets(robot):
    """DLS converges to random targets generated by FK of valid joint states."""
    rng = np.random.default_rng(7)
    limits = robot.joint_limits
    for _ in range(15):
        q_true = rng.uniform(limits[:, 0] * 0.7, limits[:, 1] * 0.7)
        target = robot.fk(q_true)
        q, err = solve_ik_dls(robot, target, np.zeros(6), damping=0.05, max_iters=200, tol_m=1e-5)
        assert err < 1e-3
        assert np.all(q >= limits[:, 0] - 1e-12)
        assert np.all(q <= limits[:, 1] + 1e-12)


def test_ik_respects_joint_limits_on_unreachable_target(robot):
    """A far-beyond-reach target must not push the solution out of limits."""
    target = np.array([0.0, 0.0, 2.0 * robot.reach])
    q, err = solve_ik_dls(robot, target, np.zeros(6), damping=0.05, max_iters=80)
    assert np.all(q >= robot.joint_limits[:, 0] - 1e-12)
    assert np.all(q <= robot.joint_limits[:, 1] + 1e-12)
    assert err > 0.05  # genuinely unreachable


def test_ik_tracks_smooth_trajectory_with_warm_start(robot):
    """Warm-started IK keeps tracking error small along a smooth joint path."""
    rng = np.random.default_rng(3)
    n = 40
    t = np.linspace(0.0, 2.0 * np.pi, n)
    q_path = np.stack([0.6 * np.sin(t + i) for i in range(6)], axis=1)
    targets = np.array([robot.fk(q) for q in q_path])
    q_prev = np.zeros(6)
    errors = []
    for target in targets:
        q_prev, err = solve_ik_dls(robot, target, q_prev, damping=0.05, max_iters=100, tol_m=1e-5)
        errors.append(err)
    assert max(errors) < 5e-3


def test_retarget_synthetic_landmarks(cfg, robot):
    """Synthetic human landmarks produce valid 6-DOF angles with low IK error."""
    landmarks, fps = make_demo_landmarks(n_frames=60, fps=30.0)
    assert fps == 30.0
    angles, info = retarget_landmarks_to_angles(landmarks, robot, cfg, side="auto")
    assert angles.shape == (60, 6)
    assert np.all(np.isfinite(angles))
    limits = np.asarray(cfg["robot"]["joint_limits_deg"], dtype=float)
    assert np.all(angles >= limits[:, 0])
    assert np.all(angles <= limits[:, 1])
    assert info["side"] == "right"  # both arms visible -> deterministic tie-break
    assert info["frames_held"] == 0
    assert info["mean_pos_err_m"] < 5e-3


def test_retarget_holds_target_when_visibility_low(cfg, robot):
    """Frames without a visible arm hold the previous IK target (frozen pose)."""
    landmarks, _ = make_demo_landmarks(n_frames=30)
    landmarks[:, :, 3] = 0.0
    angles, info = retarget_landmarks_to_angles(landmarks, robot, cfg, side="right")
    assert info["frames_held"] == 30
    # The pose settles within the first frames (geometric convergence), then
    # stays frozen (same target, warm start): no jumps beyond settling drift.
    assert np.abs(np.diff(angles, axis=0)).max() < 2.0
    assert np.allclose(angles[5:], angles[5], atol=1e-3)
